    private void changeButtonColors(JButton clickedButton) {
        for (JButton button : buttons) {
            if (button == clickedButton) {
                button.setBackground(new Color(255, 102, 102));
            } else {
                button.setBackground(new Color(255, 255, 255));
            }
        }
    }

