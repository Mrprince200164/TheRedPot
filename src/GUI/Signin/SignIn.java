    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        final String HIDE_ICON_PATH = "/Resources/eye.png"; // Icon to show when password is VISIBLE (implies next click will HIDE)
        final String SHOW_ICON_PATH = "/Resources/hide.png";  // Icon to show when password is HIDDEN (implies next click will SHOW)

// Get the current echo character of the password field
        char currentEchoChar = jPasswordField1.getEchoChar();

// Check if the password is currently hidden (default echo char is often '\u2022' or '*')
        if (currentEchoChar == '\u2022' || currentEchoChar == '*') {
            // Password is currently hidden, so show it
            try {
                ImageIcon icon = new ImageIcon(getClass().getResource(HIDE_ICON_PATH));
                jButton1.setIcon(icon);
            } catch (NullPointerException e) {
                System.err.println("Error loading hide icon: " + HIDE_ICON_PATH + ". Make sure the file exists in your resources.");
                // Optionally, set a default icon or handle the error gracefully
            }
            jPasswordField1.setEchoChar('\u0000'); // Set to null character to show text
        } else {
            // Password is currently visible, so hide it
            try {
                ImageIcon icon = new ImageIcon(getClass().getResource(SHOW_ICON_PATH));
                jButton1.setIcon(icon);
            } catch (NullPointerException e) {
                System.err.println("Error loading show icon: " + SHOW_ICON_PATH + ". Make sure the file exists in your resources.");
                // Optionally, set a default icon or handle the error gracefully
            }
            jPasswordField1.setEchoChar('\u2022'); // Set back to bullet to hide text
        }

    }//GEN-LAST:event_jButton1ActionPerformed

